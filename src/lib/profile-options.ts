/** Classes the profile form accepts. 2027 is the public ranking class; nearby years match the sample profile and the save check. */
export const GRADUATION_CLASSES = ["2025", "2026", "2027", "2028", "2029", "2030", "2031", "2032"] as const;

export function isGraduationClass(value: string) {
  return (GRADUATION_CLASSES as readonly string[]).includes(value);
}

export function graduationClassOptions(current: string): ProfileOption[] {
  const options = GRADUATION_CLASSES.map((year) => ({
    value: year,
    label: `Class of ${year}`,
  }));
  return optionsIncludingCurrent(options, current, /^\d{4}$/.test(current.trim()) ? `Class of ${current.trim()}` : current.trim());
}

export function optionsIncludingCurrent(
  options: readonly ProfileOption[],
  current: string,
  fallbackLabel = current.trim(),
): ProfileOption[] {
  const value = current.trim();
  if (!value || options.some((option) => option.value === value)) return [...options];
  return [{ value, label: fallbackLabel || value }, ...options];
}
